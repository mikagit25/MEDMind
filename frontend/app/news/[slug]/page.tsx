function fmtDate(s: string | null, lang: Lang): string {
  if (!s) return "";
  try { return new Intl.DateTimeFormat(lang, { year: "numeric", month: "long", day: "numeric" }).format(new Date(s)); }
  catch { return s.split("T")[0]; }
}

function fmtDateShort(s: string | null, lang: Lang): string {
  if (!s) return "";
  try { return new Intl.DateTimeFormat(lang, { month: "short", day: "numeric" }).format(new Date(s)); }
  catch { return s.split("T")[0]; }
}

const API = process.env.NEXT_PUBLIC_API_URL ?? "/api/v1";

export default function NewsDetailPage() {
  const params = useParams();
  const searchParams = useSearchParams();
  const router = useRouter();
  const slug = params?.slug as string;
  const { locale, setLocale } = useI18n();
  const langParam = searchParams?.get("locale") as Lang | null;
  const lang = (langParam && LANGS.some(l => l.value === langParam) ? langParam
    : LANGS.some(l => l.value === locale) ? locale as Lang : "en");
  const ui = UI[lang];

  const [article, setArticle]       = useState<NewsDetail | null>(null);
  const [related, setRelated]       = useState<RelatedArticle[]>([]);
  const [moreNews, setMoreNews]     = useState<NewsPreview[]>([]);
  const [loading, setLoading]       = useState(true);
  const [notFound, setNotFound]     = useState(false);

  // Sync global i18n locale to the URL param when it differs (e.g. external link with ?locale=ru)
  useEffect(() => {
    if (langParam && LANGS.some(l => l.value === langParam) && langParam !== locale) {
      setLocale(langParam as import("../../../lib/i18n").Locale);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [langParam]);

  useEffect(() => {
    if (!slug) return;
    setLoading(true);
    Promise.all([
      fetch(`${API}/news/${slug}?locale=${lang}`),
      fetch(`${API}/news/${slug}/related-articles?locale=${lang}`),
    ]).then(async ([newsRes, relRes]) => {
      if (newsRes.status === 404) { setNotFound(true); return; }
      const [newsData, relData] = await Promise.all([newsRes.json(), relRes.ok ? relRes.json() : []]);
      setArticle(newsData);
      setRelated(Array.isArray(relData) ? relData : []);
    }).catch(() => setNotFound(true))
      .finally(() => setLoading(false));
  }, [slug, lang]);

  // Fetch more news in same category after article loads
  useEffect(() => {
    if (!article) return;
    fetch(`${API}/news?category=${article.category}&locale=${lang}&limit=7`)
      .then(r => r.ok ? r.json() : [])
      .then((data: NewsPreview[]) => {
        if (Array.isArray(data)) {
          setMoreNews(data.filter(n => n.slug !== slug).slice(0, 4));
        }
      })
      .catch(() => {});
  }, [article, lang, slug]);

  const isPreprint = article?.source_name === "medRxiv";
  const isTeacher  = article?.author_display_name != null && !["WHO", "PubMed", "medRxiv"].includes(article?.source_name ?? "");

  if (loading) return (
    <div className="min-h-screen bg-bg flex items-center justify-center">
      <div className="w-8 h-8 border-2 border-ink border-t-transparent rounded-full animate-spin" />
    </div>
  );

  if (notFound || !article) return (
    <div className="min-h-screen bg-bg flex flex-col items-center justify-center gap-4">
      <div className="text-5xl">📰</div>
      <p className="font-syne text-ink-2">Article not found.</p>
      <Link href="/news" className="font-syne font-semibold text-sm text-red hover:underline">{ui.back}</Link>
    </div>
  );

  return (
    <div className="min-h-screen bg-bg" dir={lang === "ar" ? "rtl" : "ltr"}>
      {/* Nav */}
      <nav className="bg-surface border-b border-border sticky top-0 z-50">
        <div className="max-w-4xl mx-auto px-4 sm:px-6 py-3 flex items-center justify-between gap-3">
          <Link href="/" className="font-syne font-extrabold text-xl tracking-tight text-ink flex-shrink-0">
            Med<span className="text-red">Mind</span>
          </Link>
          <div className="hidden md:flex items-center gap-1 text-sm font-syne font-semibold text-ink-2">
            <Link href="/articles" className="hover:text-ink px-3 py-2 transition-colors">
              {lang === "ru" ? "Статьи" : lang === "ar" ? "مقالات" : lang === "de" ? "Artikel" : lang === "fr" ? "Articles" : lang === "es" ? "Artículos" : lang === "tr" ? "Makaleler" : "Articles"}
            </Link>
            <Link href="/news" className="text-ink hover:text-red px-3 py-2 transition-colors">
              {lang === "ru" ? "Новости" : lang === "ar" ? "أخبار" : lang === "de" ? "Nachrichten" : lang === "fr" ? "Actualités" : lang === "es" ? "Noticias" : lang === "tr" ? "Haberler" : "News"}
            </Link>
            <Link href="/calculators" className="hover:text-ink px-3 py-2 transition-colors">
              {lang === "ru" ? "Калькуляторы" : lang === "ar" ? "آلات حاسبة" : lang === "de" ? "Rechner" : lang === "fr" ? "Calculateurs" : lang === "es" ? "Calculadoras" : lang === "tr" ? "Hesap makineleri" : "Calculators"}
            </Link>
          </div>
          <select
            value={lang}
            onChange={e => {
              const next = e.target.value as import("../../../lib/i18n").Locale;
              setLocale(next);
              router.push(`/news/${slug}?locale=${next}`);
            }}
            className="text-xs font-syne border border-border rounded px-1.5 py-1 bg-bg text-ink focus:outline-none"
          >
            {LANGS.map(l => <option key={l.value} value={l.value}>{l.flag}</option>)}
          </select>
        </div>
      </nav>

      <main className="max-w-4xl mx-auto px-4 sm:px-6 py-10">
        <Link href="/news" className="inline-flex items-center gap-1.5 font-syne font-semibold text-sm text-ink-2 hover:text-ink transition-colors mb-8">
          {ui.back}
        </Link>

        <article>
          {/* Category + badges */}
          <div className="flex flex-wrap items-center gap-2 mb-4">
            <span className="text-xs font-syne font-bold text-red uppercase tracking-wider">
              {getCategoryLabel(article.category, lang)}
            </span>
            <span className={`text-xs font-syne font-bold px-2 py-0.5 rounded-full ${SOURCE_BADGE[article.source_name] ?? "bg-amber-100 text-amber-800"}`}>
              {article.source_name}
            </span>
            {isPreprint && (
              <span className="text-xs font-syne px-2 py-0.5 rounded-full bg-yellow-100 text-yellow-800 dark:bg-yellow-900/30 dark:text-yellow-300">
                ⚠ {ui.preprint}
              </span>
            )}
          </div>

          {/* Title */}
          <h1 className="font-syne font-extrabold text-2xl sm:text-3xl lg:text-4xl text-ink leading-tight mb-6">
            {article.title}
          </h1>

          {/* Meta strip */}
          <div className="grid sm:grid-cols-2 gap-3 bg-surface border border-border rounded-xl p-4 mb-8 text-sm">
            <div>
              <span className="block font-syne font-semibold text-xs text-ink-3 uppercase tracking-wide mb-0.5">{ui.source}</span>
              <span className="font-syne font-semibold text-ink">{article.source_name}</span>
            </div>
            {article.source_doi && (
              <div>
                <span className="block font-syne font-semibold text-xs text-ink-3 uppercase tracking-wide mb-0.5">{ui.doi}</span>
                <a href={`https://doi.org/${article.source_doi}`} target="_blank" rel="noopener noreferrer"
                  className="font-mono text-xs text-red hover:underline break-all">{article.source_doi}</a>
              </div>
            )}
            {article.original_published_at && (
              <div>
                <span className="block font-syne font-semibold text-xs text-ink-3 uppercase tracking-wide mb-0.5">{ui.pub_date}</span>
                <span className="text-ink">{fmtDate(article.original_published_at, lang)}</span>
              </div>
            )}
            {isTeacher && article.author_display_name && (
              <div>
                <span className="block font-syne font-semibold text-xs text-ink-3 uppercase tracking-wide mb-0.5">{ui.author}</span>
                <span className="text-ink">{article.author_display_name}</span>
              </div>
            )}
          </div>

          {/* Body */}
          <div className="space-y-5 mb-10">
            {article.summary.split(/\n\n+/).map((para, i) => (
              <p key={i} className="text-sm sm:text-base leading-relaxed text-ink">{para}</p>
            ))}
          </div>

          {/* Disclaimer */}
          <div className="bg-amber-50 dark:bg-amber-900/10 border border-amber-200 dark:border-amber-800 rounded-xl p-4 mb-6">
            <p className="text-xs text-amber-800 dark:text-amber-300 font-syne leading-relaxed">
              <span className="font-bold">{ui.disclaimer_label}: </span>{ui.disclaimer}
            </p>
          </div>

          {/* CTA */}
          <a href={article.source_url} target="_blank" rel="noopener noreferrer"
            className="inline-flex items-center gap-2 font-syne font-bold text-sm bg-ink text-[#f0ede8] px-6 py-3 rounded-xl hover:bg-red transition-colors">
            {ui.read_original}
          </a>
        </article>

        {/* ── Related MedMind articles ──────────────────────────────────────── */}
        {related.length > 0 && (
          <section className="mt-14 border-t border-border pt-10">
            <h2 className="font-syne font-extrabold text-xl text-ink mb-6">{ui.related_articles}</h2>
            <div className="grid sm:grid-cols-2 gap-4">
              {related.map(r => (
                <Link key={r.slug} href={`/articles/${r.slug}`}
                  className="group bg-surface border border-border rounded-xl p-5 hover:border-ink hover:shadow-sm transition-all">
                  <span className="text-xs font-syne font-bold text-red uppercase tracking-wide block mb-2">
                    {getCategoryLabel(r.category, lang)}
                  </span>
                  <h3 className="font-syne font-bold text-sm text-ink group-hover:text-red transition-colors leading-snug mb-2 line-clamp-2">
                    {r.title}
                  </h3>
                  <p className="text-xs text-ink-2 leading-relaxed line-clamp-3">{r.excerpt}</p>
                  <span className="mt-3 inline-flex items-center gap-1 text-xs font-syne font-semibold text-red">
                    {lang === "ru" ? "Читать статью" : lang === "ar" ? "اقرأ المقالة" : lang === "de" ? "Artikel lesen" : lang === "fr" ? "Lire l'article" : lang === "es" ? "Leer artículo" : lang === "tr" ? "Makaleyi oku" : "Read article"}
                    <svg className="w-3 h-3 group-hover:translate-x-0.5 transition-transform" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5"><path d="M5 12h14M12 5l7 7-7 7"/></svg>
                  </span>
                </Link>
              ))}
            </div>
          </section>
        )}

        {/* ── More news in this category ────────────────────────────────────── */}
        {moreNews.length > 0 && (
          <section className="mt-14 border-t border-border pt-10">
            <div className="flex items-center justify-between mb-6">
              <h2 className="font-syne font-extrabold text-xl text-ink">{ui.more_in_category}</h2>
              <Link href={`/news?category=${article.category}`}
                className="text-xs font-syne font-semibold text-red hover:underline">
                {ui.all_news}
              </Link>
            </div>
            <div className="grid sm:grid-cols-2 gap-4">
              {moreNews.map(n => (
                <Link key={n.slug} href={`/news/${n.slug}?locale=${lang}`}
                  className="group bg-surface border border-border rounded-xl p-5 hover:border-red/40 hover:shadow-sm transition-all flex flex-col">
                  <div className="flex items-center justify-between gap-2 mb-3">
                    <span className={`text-xs font-syne font-bold px-2 py-0.5 rounded-full flex-shrink-0 ${SOURCE_BADGE[n.source_name] ?? "bg-amber-100 text-amber-800"}`}>
                      {n.source_name}
                    </span>
                    <span className="text-xs text-ink-3 font-syne">
                      {fmtDateShort(n.original_published_at || n.fetched_at, lang)}
                    </span>
                  </div>
                  <h3 className="font-syne font-bold text-sm text-ink group-hover:text-red transition-colors leading-snug mb-2 line-clamp-3 flex-1">
                    {n.title}
                  </h3>
                  <p className="text-xs text-ink-2 leading-relaxed line-clamp-2 mb-3">
                    {n.summary_excerpt}
                  </p>
                  <span className="inline-flex items-center gap-1 text-xs font-syne font-semibold text-red mt-auto">
                    {lang === "ru" ? "Читать далее" : lang === "ar" ? "اقرأ المزيد" : lang === "de" ? "Weiterlesen" : lang === "fr" ? "Lire la suite" : lang === "es" ? "Leer más" : lang === "tr" ? "Devamını oku" : "Read more"}
                    <svg className="w-3 h-3 group-hover:translate-x-0.5 transition-transform" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5"><path d="M5 12h14M12 5l7 7-7 7"/></svg>
                  </span>
                </Link>
              ))}
            </div>
            <div className="mt-6 text-center">
              <Link href="/news"
                className="inline-flex items-center gap-2 font-syne font-semibold text-sm border border-border text-ink-2 hover:text-ink hover:border-ink px-5 py-2.5 rounded-xl transition-all">
                {lang === "ru" ? "Все медицинские новости" : lang === "ar" ? "جميع الأخبار الطبية" : lang === "de" ? "Alle medizinischen Nachrichten" : lang === "fr" ? "Toutes les actualités médicales" : lang === "es" ? "Todas las noticias médicas" : lang === "tr" ? "Tüm tıp haberleri" : "All medical news"}
              </Link>
            </div>
          </section>
        )}

        <CommentsBlock contentType="news" slug={slug} />

        {/* Footer */}
        <div className="mt-14 pt-8 border-t border-border flex flex-wrap justify-center gap-4 text-xs text-ink-3 font-syne">
          <Link href="/news" className="hover:text-ink transition-colors">{lang === "ru" ? "Новости" : "News"}</Link>
          <span>·</span>
          <Link href="/articles" className="hover:text-ink transition-colors">{lang === "ru" ? "Статьи" : "Articles"}</Link>
          <span>·</span>
          <Link href="/calculators" className="hover:text-ink transition-colors">{lang === "ru" ? "Калькуляторы" : "Calculators"}</Link>
          <span>·</span>
          <Link href="/symptoms" className="hover:text-ink transition-colors">{lang === "ru" ? "Симптомы" : "Symptoms"}</Link>
        </div>
      </main>
    </div>
  );
}
